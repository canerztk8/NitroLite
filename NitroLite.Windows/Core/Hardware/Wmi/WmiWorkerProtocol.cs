using System.Buffers;
using System.Buffers.Binary;
using System.IO;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.Json.Serialization;

namespace NitroLite.Core.Hardware.Wmi;

/// <summary>
/// The closed set of things the elevated worker can be asked to do.
/// <para>
/// There is deliberately no <c>InvokeWmi(method, payload)</c> member. The worker runs with an administrator token, so
/// its attack surface is exactly this enum: if a command is not listed here, no amount of crafted JSON can make the
/// worker call an arbitrary WMI method. Adding a capability means editing this list, which is a change a reviewer can
/// see.
/// </para>
/// </summary>
public enum WmiWorkerCommand
{
    /// <summary>Liveness check. Touches nothing.</summary>
    Ping = 0,

    /// <summary>Which interfaces this machine exposes.</summary>
    GetWorkerCapabilities = 1,

    /// <summary>Sensors: system info bytes, fan speeds, active mode, fan behaviour.</summary>
    ReadTelemetry = 2,

    /// <summary>Everything the window draws: mode, fan modes and speeds, MUX, battery limit.</summary>
    ReadDeviceState = 3,

    /// <summary>CPU and GPU fan behaviour (Auto / Max / Custom).</summary>
    SetFanBehavior = 4,

    /// <summary>CPU and GPU fan percentage.</summary>
    SetFanSpeed = 5,

    /// <summary>Platform power profile.</summary>
    SetOperatingMode = 6,

    /// <summary>MUX switch.</summary>
    SetMuxMode = 7,

    /// <summary>Battery charge limit, when WMID_GUID5 exists.</summary>
    SetBatteryLimit = 8,

    /// <summary>Keyboard backlight state: brightness, colour and the raw structure.</summary>
    GetKeyboardBacklight = 9,

    /// <summary>
    /// The full keyboard lighting write: four zone colours plus an effect, its speed, brightness and direction.
    /// Replaces the single-colour write that used to live at this value; the number is kept so the wire format does
    /// not change for a rename.
    /// </summary>
    SetKeyboardLighting = 10,

    /// <summary>CoolBoost state, from <c>APGeAction.GetFunction(0x207)</c>.</summary>
    GetCoolBoost = 11,

    /// <summary>CoolBoost on or off, through <c>APGeAction.SetFunction</c>.</summary>
    SetCoolBoost = 12,

    // 13 and 14 were the LCD overdrive get/set commands. They are retired: never reuse these numbers, and do not
    // renumber the commands below, because the app and the elevated worker may be different builds.

    /// <summary>Windows-key lock, through <c>SetGamingProfile</c>. Write-only: the firmware has no getter.</summary>
    SetWinKeyLock = 15,

    /// <summary>The 30-second keyboard backlight timeout, from <c>APGeAction.GetFunction</c>.</summary>
    GetBacklightTimeout = 16,

    /// <summary>The 30-second keyboard backlight timeout, through <c>APGeAction.SetFunction</c>.</summary>
    SetBacklightTimeout = 17,

    /// <summary>
    /// Whether the worker hands manual fans back to the firmware when this client disappears (<c>handBack</c>, a
    /// boolean). The default is true: the window's fan curve is what makes a fixed speed safe, and a crashed window
    /// leaves nothing watching. Only the one-shot <c>--fan</c> command sends false, because leaving the speed in place
    /// after it exits is what it is documented to do. Touches no hardware.
    /// </summary>
    SetFanHandBack = 18
}

/// <summary>
/// One message from the window to the worker.
/// <para>
/// The first message on a connection is always a <see cref="WmiWorkerProtocol.TypeHello"/> carrying the nonce; only
/// after that is accepted does the worker read a <see cref="WmiWorkerProtocol.TypeCommand"/>. A connection that sends
/// a command first is closed without an answer.
/// </para>
/// <para>
/// The nonce is generated by the window and never leaves the pipe. It used to travel on the helper's command line,
/// where <c>Win32_Process.CommandLine</c> handed it to any process running as the same user; the worker now
/// authenticates its caller by process id and echoes the nonce back so the window can prove it is talking to the
/// helper it started.
/// </para>
/// </summary>
public sealed record WmiWorkerRequest
{
    [JsonPropertyName("type")]
    public string Type { get; init; } = WmiWorkerProtocol.TypeCommand;

    /// <summary>The single-use handshake value. Only read on the hello message.</summary>
    [JsonPropertyName("nonce")]
    public string Nonce { get; init; } = "";

    /// <summary>Serialised as a number: renaming an enum member must not change the wire format.</summary>
    [JsonPropertyName("command")]
    public WmiWorkerCommand Command { get; init; } = WmiWorkerCommand.Ping;

    /// <summary>Command arguments. Absent for the read-only commands.</summary>
    [JsonPropertyName("args")]
    public JsonObject? Args { get; init; }
}

/// <summary>One message from the worker back to the window.</summary>
public sealed record WmiWorkerResponse
{
    [JsonPropertyName("type")]
    public string Type { get; init; } = WmiWorkerProtocol.TypeResult;

    [JsonPropertyName("ok")]
    public bool Ok { get; init; }

    /// <summary>Stable token from <see cref="WmiOperationResult"/>; empty on success.</summary>
    [JsonPropertyName("errorCode")]
    public string ErrorCode { get; init; } = "";

    [JsonPropertyName("error")]
    public string Error { get; init; } = "";

    /// <summary>
    /// The handshake value the caller sent, echoed back on the welcome. The window compares it with the one it
    /// generated: a reply that does not carry it did not come from the helper this process started.
    /// </summary>
    [JsonPropertyName("nonce")]
    public string Nonce { get; init; } = "";

    [JsonPropertyName("data")]
    public JsonObject? Data { get; init; }

    public static WmiWorkerResponse FromResult(WmiOperationResult result) => new()
    {
        Type = WmiWorkerProtocol.TypeResult,
        Ok = result.Ok,
        ErrorCode = result.ErrorCode,
        Error = result.Error,
        Data = result.Data
    };

    public static WmiWorkerResponse Failure(string errorCode, string error) => new()
    {
        Type = WmiWorkerProtocol.TypeResult,
        Ok = false,
        ErrorCode = errorCode,
        Error = error
    };

    /// <summary>Turns the wire message back into the result type the executor speaks.</summary>
    public WmiOperationResult ToResult() => Ok
        ? WmiOperationResult.Success(Data)
        : WmiOperationResult.Failure(string.IsNullOrEmpty(ErrorCode) ? WmiOperationResult.CodeWmiFailed : ErrorCode, Error);
}

/// <summary>
/// The wire format: a four-byte little-endian length followed by that many bytes of UTF-8 JSON.
/// <para>
/// Length-prefixed rather than newline-delimited because the payload is JSON, and JSON written by a serializer may
/// contain newlines. The cap exists so a buggy or hostile peer cannot make the worker allocate a gigabyte by sending
/// a length header that promises one.
/// </para>
/// </summary>
public static class WmiWorkerProtocol
{
    /// <summary>Largest frame either side will read. Every real message is a few hundred bytes.</summary>
    public const int MaxFrameBytes = 1024 * 1024;

    /// <summary>First message on a connection: proves the caller knows the nonce.</summary>
    public const string TypeHello = "hello";

    /// <summary>Worker's answer to an accepted hello.</summary>
    public const string TypeWelcome = "welcome";

    /// <summary>A command from the window.</summary>
    public const string TypeCommand = "command";

    /// <summary>The worker's answer to a command.</summary>
    public const string TypeResult = "result";

    private static readonly JsonSerializerOptions Options = new()
    {
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
        WriteIndented = false
    };

    /// <summary>Bytes of the little-endian length that precedes every payload.</summary>
    private const int FrameHeaderBytes = 4;

    /// <summary>First guess at a frame's size. A telemetry reply is a few hundred bytes; the buffer grows if not.</summary>
    private const int InitialFrameBytes = 512;

    public static string Serialize(WmiWorkerRequest request) => JsonSerializer.Serialize(request, Options);

    public static string Serialize(WmiWorkerResponse response) => JsonSerializer.Serialize(response, Options);

    public static WmiWorkerRequest? DeserializeRequest(string json)
    {
        try
        {
            return JsonSerializer.Deserialize<WmiWorkerRequest>(json, Options);
        }
        catch (JsonException)
        {
            return null;
        }
    }

    /// <summary>Wraps a payload in the length prefix. Exposed so the framing can be tested without a pipe.</summary>
    public static byte[] Frame(string json)
    {
        var payload = Encoding.UTF8.GetBytes(json);
        var frame = new byte[FrameHeaderBytes + payload.Length];
        BinaryPrimitives.WriteInt32LittleEndian(frame.AsSpan(0, FrameHeaderBytes), payload.Length);
        payload.CopyTo(frame, FrameHeaderBytes);
        return frame;
    }

    /// <summary>Writes one framed message and flushes, so the peer is not left waiting on a buffer.</summary>
    public static async Task WriteAsync(Stream stream, string json, CancellationToken cancellationToken = default)
    {
        var frame = Frame(json);
        await stream.WriteAsync(frame, cancellationToken).ConfigureAwait(false);
        await stream.FlushAsync(cancellationToken).ConfigureAwait(false);
    }

    /// <summary>
    /// Writes one request. The JSON is serialized straight into a pooled buffer that already holds room for the
    /// length prefix, so a message costs one buffer rent and one write instead of a string, a payload array and a
    /// second array to copy both into.
    /// </summary>
    public static Task WriteAsync(Stream stream, WmiWorkerRequest request, CancellationToken cancellationToken = default) =>
        WriteFrameAsync(stream, request, cancellationToken);

    /// <inheritdoc cref="WriteAsync(Stream, WmiWorkerRequest, CancellationToken)"/>
    public static Task WriteAsync(Stream stream, WmiWorkerResponse response, CancellationToken cancellationToken = default) =>
        WriteFrameAsync(stream, response, cancellationToken);

    /// <summary>
    /// Reads one framed message. Returns null when the peer closed the connection or sent a frame that cannot be
    /// trusted (a length outside 1..<see cref="MaxFrameBytes"/>), which the caller treats as a disconnect.
    /// </summary>
    public static async Task<string?> ReadAsync(Stream stream, CancellationToken cancellationToken = default)
    {
        var frame = await ReadFrameAsync(stream, cancellationToken).ConfigureAwait(false);
        if (frame is null) return null;

        var (buffer, length) = frame.Value;
        try
        {
            return Encoding.UTF8.GetString(buffer, 0, length);
        }
        finally
        {
            ArrayPool<byte>.Shared.Return(buffer);
        }
    }

    /// <summary>
    /// Reads one request, deserializing from the frame's bytes rather than from a string. The result keeps a closed
    /// connection apart from a frame that would not parse, because the worker answers the second with an error and
    /// keeps serving while the first ends the loop.
    /// </summary>
    public static async Task<WmiWorkerReadResult> ReadRequestAsync(Stream stream, CancellationToken cancellationToken = default)
    {
        var frame = await ReadFrameAsync(stream, cancellationToken).ConfigureAwait(false);
        if (frame is null) return new WmiWorkerReadResult(null, Closed: true);

        var (buffer, length) = frame.Value;
        try
        {
            return new WmiWorkerReadResult(
                JsonSerializer.Deserialize<WmiWorkerRequest>(buffer.AsSpan(0, length), Options),
                Closed: false);
        }
        catch (JsonException)
        {
            return new WmiWorkerReadResult(null, Closed: false);
        }
        finally
        {
            ArrayPool<byte>.Shared.Return(buffer);
        }
    }

    /// <summary>
    /// Reads one response. Null means the connection closed or the frame would not parse; the client treats both the
    /// same way, because either one means the elevated path is gone.
    /// </summary>
    public static async Task<WmiWorkerResponse?> ReadResponseAsync(Stream stream, CancellationToken cancellationToken = default)
    {
        var frame = await ReadFrameAsync(stream, cancellationToken).ConfigureAwait(false);
        if (frame is null) return null;

        var (buffer, length) = frame.Value;
        try
        {
            return JsonSerializer.Deserialize<WmiWorkerResponse>(buffer.AsSpan(0, length), Options);
        }
        catch (JsonException)
        {
            return null;
        }
        finally
        {
            ArrayPool<byte>.Shared.Return(buffer);
        }
    }

    private static async Task WriteFrameAsync<T>(Stream stream, T message, CancellationToken cancellationToken)
    {
        var buffer = new PooledFrameWriter(InitialFrameBytes);
        try
        {
            using (var writer = new Utf8JsonWriter(buffer))
            {
                JsonSerializer.Serialize(writer, message, Options);
            }

            var frame = buffer.FrameSpan;
            BinaryPrimitives.WriteInt32LittleEndian(frame, frame.Length - FrameHeaderBytes);
            await stream.WriteAsync(buffer.Frame, cancellationToken).ConfigureAwait(false);
            await stream.FlushAsync(cancellationToken).ConfigureAwait(false);
        }
        finally
        {
            buffer.Return();
        }
    }

    /// <summary>
    /// Reads the length prefix and then exactly that many bytes, both into pooled buffers. The caller owns the
    /// payload buffer and returns it; the header buffer is returned here.
    /// </summary>
    private static async Task<(byte[] Buffer, int Length)?> ReadFrameAsync(Stream stream, CancellationToken cancellationToken)
    {
        var header = ArrayPool<byte>.Shared.Rent(FrameHeaderBytes);
        int length;
        try
        {
            await stream.ReadExactlyAsync(header.AsMemory(0, FrameHeaderBytes), cancellationToken).ConfigureAwait(false);
            length = BinaryPrimitives.ReadInt32LittleEndian(header.AsSpan(0, FrameHeaderBytes));
        }
        catch (EndOfStreamException)
        {
            return null;
        }
        catch (IOException)
        {
            return null;
        }
        finally
        {
            ArrayPool<byte>.Shared.Return(header);
        }

        if (length <= 0 || length > MaxFrameBytes) return null;

        var payload = ArrayPool<byte>.Shared.Rent(length);
        try
        {
            await stream.ReadExactlyAsync(payload.AsMemory(0, length), cancellationToken).ConfigureAwait(false);
        }
        catch (EndOfStreamException)
        {
            ArrayPool<byte>.Shared.Return(payload);
            return null;
        }
        catch (IOException)
        {
            ArrayPool<byte>.Shared.Return(payload);
            return null;
        }

        return (payload, length);
    }

    /// <summary>
    /// A pooled <see cref="IBufferWriter{T}"/> that starts four bytes in, so the length prefix can be written into the
    /// same buffer the JSON goes into and the whole frame leaves in one write.
    /// </summary>
    private sealed class PooledFrameWriter : IBufferWriter<byte>
    {
        private byte[] _buffer;
        private int _written;
        private bool _returned;

        public PooledFrameWriter(int initialCapacity)
        {
            _buffer = ArrayPool<byte>.Shared.Rent(Math.Max(initialCapacity, FrameHeaderBytes));
            _written = FrameHeaderBytes;
        }

        /// <summary>The reserved prefix plus everything written after it.</summary>
        public ReadOnlyMemory<byte> Frame => _buffer.AsMemory(0, _written);

        /// <summary>The same bytes, writable, so the length prefix can be filled in after the JSON is written.</summary>
        public Span<byte> FrameSpan => _buffer.AsSpan(0, _written);

        public void Advance(int count) => _written += count;

        public Memory<byte> GetMemory(int sizeHint = 0)
        {
            Ensure(sizeHint);
            return _buffer.AsMemory(_written);
        }

        public Span<byte> GetSpan(int sizeHint = 0)
        {
            Ensure(sizeHint);
            return _buffer.AsSpan(_written);
        }

        /// <summary>Hands the buffer back. Not <c>Dispose</c>: this type owns no handle, only a rented array.</summary>
        public void Return()
        {
            if (_returned) return;
            _returned = true;
            ArrayPool<byte>.Shared.Return(_buffer);
            _buffer = Array.Empty<byte>();
            _written = 0;
        }

        private void Ensure(int sizeHint)
        {
            if (sizeHint < 1) sizeHint = 1;
            if (_buffer.Length - _written >= sizeHint) return;

            var next = ArrayPool<byte>.Shared.Rent(Math.Max(_buffer.Length * 2, _written + sizeHint));
            _buffer.AsSpan(0, _written).CopyTo(next);
            ArrayPool<byte>.Shared.Return(_buffer);
            _buffer = next;
        }
    }

    /// <summary>
    /// Constant-time comparison of the handshake value. A byte-by-byte early exit would leak the nonce's prefix to a
    /// caller that can time the rejection, which is the one thing the nonce exists to prevent.
    /// </summary>
    public static bool NonceMatches(string? expected, string? actual)
    {
        if (string.IsNullOrEmpty(expected) || string.IsNullOrEmpty(actual)) return false;
        if (expected.Length != actual.Length) return false;

        var diff = 0;
        for (int i = 0; i < expected.Length; i++)
        {
            diff |= char.ToLowerInvariant(expected[i]) ^ char.ToLowerInvariant(actual[i]);
        }

        return diff == 0;
    }
}

/// <summary>
/// What one read off the pipe produced. <see cref="Closed"/> and a null <see cref="Request"/> together mean the peer
/// went away; a null request with <see cref="Closed"/> false means it sent something that is not a request.
/// </summary>
public readonly record struct WmiWorkerReadResult(WmiWorkerRequest? Request, bool Closed)
{
    /// <summary>The peer sent a frame that is not a request.</summary>
    public bool Malformed => !Closed && Request is null;
}
